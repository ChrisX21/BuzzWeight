-- Baseline schema for the sensors table so the repo is the source of truth.
-- Captures the state that previously only existed in the pg_dump backup.
-- Idempotent so it can run against environments where the table already exists.

CREATE TABLE IF NOT EXISTS public.sensors (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor character varying DEFAULT ''::character varying NOT NULL,
    value real NOT NULL,
    "trailerId" integer NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS sensors_created_at_idx ON public.sensors USING btree (created_at);
CREATE INDEX IF NOT EXISTS "sensors_trailerId_idx" ON public.sensors USING btree ("trailerId");

ALTER TABLE public.sensors ENABLE ROW LEVEL SECURITY;
